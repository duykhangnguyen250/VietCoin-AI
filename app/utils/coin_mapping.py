def get_coin_info(label: str):
    if not label:
        return {"display_name": "Chưa xác định", "han": "N/A", "description": "Vui lòng chụp ảnh rõ nét hơn để hệ thống nhận diện."}
    
    def normalize(s):
        return str(s).replace("_", " ").strip().lower()

    target = normalize(label)
    for key, value in COIN_MAPPING.items():
        if normalize(key) == target:
            return value
            
    return {
        "display_name": label,
        "han": "N/A", 
        "description": f"Dữ liệu lịch sử cho nhãn '{label}' đang được các chuyên gia của chúng tôi cập nhật thêm."
    }

